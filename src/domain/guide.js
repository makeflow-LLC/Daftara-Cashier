const BY_ID = new Map(TOPICS.map((t) => [t.id, t]));
const BY_ROUTE = new Map(TOPICS.flatMap((t) => t.routes.map((r) => [r, t])));

export function topicById(id) {
  return BY_ID.get(id) || null;
}

/** موضوع الصفحة المفتوحة: path من الرابط (مع ?… أو بدونه). */
export function topicForPath(path) {
  return BY_ROUTE.get(String(path || '/').split('?')[0] || '/') || null;
}

export function topicsOf(catId) {
  return TOPICS.filter((t) => t.cat === catId);
}

/** نص الموضوع كله للبحث. */
export function topicText(t) {
  return [t.title, t.why, ...t.steps, ...t.tips, t.keys || ''].join(' ');
}

/** بحث في الدليل: كل كلمات السؤال يجب أن ترد (norm = normalizeArabic). المطابق في العنوان أولًا. */
export function searchTopics(query, norm = (s) => s) {
  const words = norm(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return TOPICS.map((t) => {
    const title = norm(t.title), all = norm(topicText(t));
    if (!words.every((w) => all.includes(w))) return null;
    return { t, score: words.filter((w) => title.includes(w)).length };
  }).filter(Boolean).sort((a, b) => b.score - a.score).map((x) => x.t);
}

/** أسئلة شائعة تخص الموضوع: زرّها يفتح إحدى صفحاته، أو وُسمت باسمه (t). */
export function faqFor(topic, faq) {
  const out = [];
  for (const g of faq) {
    for (const it of g.items) {
      const path = it.go ? it.go[0].split('?')[0] : null;
      if (it.t === topic.id || (!it.t && path && topic.routes.includes(path))) out.push(it);
    }
  }
  return out;
}
