export function renderHelp(el) {
  const q = input({ type: 'search', placeholder: 'ابحث في الأسئلة…', autocomplete: 'off' });
  const body = h('div');
  let open = null;

  function item(it) {
    const isOpen = open === it.q;
    return h('div', { class: `faq ${isOpen ? 'open' : ''}` },
      h('button', { class: 'faq-q', type: 'button', 'aria-expanded': String(isOpen), onclick: () => { open = isOpen ? null : it.q; paint(); } }, h('span', null, it.q), icon(isOpen ? 'minus' : 'plus', 20)),
      isOpen ? h('div', { class: 'faq-a' }, h('p', null, it.a),
        it.go ? h('button', { class: 'btn btn-outline', type: 'button', onclick: () => navigate(it.go[0]) }, icon('chevron', 18), h('span', null, it.go[1])) : null) : null);
  }
  function paint() {
    const nq = normalizeArabic(q.value);
    const groups = FAQ.map((g) => ({ ...g, items: nq ? g.items.filter((it) => normalizeArabic(it.q + it.a).includes(nq)) : g.items })).filter((g) => g.items.length);
    fill(body, groups.length ? groups.map((g) => h('div', { class: 'section' },
      h('h2', { class: 'section-title faq-group' }, icon(g.icon, 20), g.group),
      h('div', { class: 'list faq-list' }, ...g.items.map(item))))
      : emptyState('help', 'لم نجد جوابًا', 'اسألنا مباشرة على واتساب وسنرد عليك.',
        h('button', { class: 'btn btn-wa', type: 'button', onclick: () => openFeedback('note') }, icon('chat', 22), h('span', null, 'اسألنا على واتساب'))));
  }
  q.addEventListener('input', () => { open = null; paint(); });

  el.append(header('المساعدة', { back: true }), h('div', { class: 'page' },
    h('div', { class: 'help-hero' }, icon('help', 30), h('div', null, h('strong', null, 'كيف نساعدك؟'), h('p', null, 'إجابات قصيرة عن كل شيء في التطبيق.'))),
    h('div', { class: 'search-row' }, icon('search', 20), q),
    body,
    h('div', { class: 'section' }, h('h2', { class: 'section-title' }, 'لم تجد ما تبحث عنه؟'),
      h('div', { class: 'help-contact' },
        h('button', { class: 'btn btn-wa', type: 'button', onclick: () => openLink(`https://wa.me/${SUPPORT_PHONE}?text=${encodeURIComponent('مرحبًا، عندي سؤال عن دفترة كاشير: ')}`) }, icon('chat', 22), h('span', null, 'اسألنا على واتساب')),
        h('button', { class: 'btn btn-outline', type: 'button', onclick: () => openFeedback('feature') }, icon('bulb', 22), h('span', null, 'اقترح ميزة')))),
  ));
  paint();
}
